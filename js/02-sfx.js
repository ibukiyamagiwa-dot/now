function tone(f,d,type,v,f2){const a=AC;if(!a)return;const o=a.createOscillator(),g=a.createGain(),t=a.currentTime;o.type=type||'square';o.frequency.setValueAtTime(f,t);if(f2)o.frequency.exponentialRampToValueAtTime(f2,t+d);g.gain.setValueAtTime(v||.1,t);g.gain.exponentialRampToValueAtTime(.001,t+d);o.connect(g).connect(master());o.start(t);o.stop(t+d+.02)}
function sweep(d,v,f0,f1,q){const a=AC;if(!a)return;const n=Math.max(1,a.sampleRate*d|0),b=a.createBuffer(1,n,a.sampleRate),ch=b.getChannelData(0);for(let i=0;i<n;i++)ch[i]=(Math.random()*2-1)*(1-i/n)**1.5;const s=a.createBufferSource();s.buffer=b;const fl=a.createBiquadFilter();fl.type='bandpass';fl.Q.value=q||1;const t=a.currentTime;fl.frequency.setValueAtTime(f0,t);fl.frequency.exponentialRampToValueAtTime(f1,t+d);const g=a.createGain();g.gain.value=v;s.connect(fl).connect(g).connect(master());s.start()}
function noise(d,v,fq,type){const a=AC;if(!a)return;const n=Math.max(1,a.sampleRate*d|0),b=a.createBuffer(1,n,a.sampleRate),ch=b.getChannelData(0);for(let i=0;i<n;i++)ch[i]=(Math.random()*2-1)*(1-i/n)**2;const s=a.createBufferSource();s.buffer=b;const fl=a.createBiquadFilter();fl.type=type||'bandpass';fl.frequency.value=fq||2000;const g=a.createGain();g.gain.value=v||.2;s.connect(fl).connect(g).connect(master());s.start()}
